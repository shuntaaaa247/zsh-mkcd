# mkdir -p で作成したディレクトリに同時に入るためのシェル関数
# zsh で動作する
# 例えば、~/.zsh 配下にこの mkcd.sh を置いた場合は
# ~/.zshrc の末尾に source ~/.zsh/mkcd.sh の文言を追加することで使用できる
#
# $ mkcd foo のように使う
# -p オプションにより $ mkcd aaa/bbb/ccc のように階層をまとめて作成でき、その場合は最後の ccc ディレクトリに遷移する
# また $ mkcd aaa bbb ccc のように実行すると、aaa・bbb・ccc を同じ階層に作成し、最後の ccc に遷移する
# -p は既存ディレクトリをエラーにしないため、ccc がすでに存在して中にデータがある場合も
# 上書きや削除は行われず、単に ccc に遷移するだけになる
# -- は以降をオプションとして解釈させないための区切り（-n のような名前のディレクトリにも対応するため）
mkcd() {
    mkdir -p -- "$@" && cd -- "${@: -1}"
}